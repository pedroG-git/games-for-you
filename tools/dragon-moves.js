// node tools/dragon-moves.js [count] - precomputes Dragon Match move counts so the phone doesn't have to simulate
const fs = require('fs');
const path = require('path');
const COUNT = Number(process.argv[2]) || 200;
(async () => {
  const { levelFor } = await import('../www/games/dragon/js/levels.js');
  const out = [];
  for (let n = 1; n <= COUNT; n++) {
    const L = levelFor(n);
    out.push(`${n}:[${L.v},${L.moves}]`);
  }
  const file = path.join(__dirname, '../www/games/dragon/js/moves.js');
  fs.writeFileSync(file, `// Generated by tools/dragon-moves.js: level -> [variant, moves]. Levels after these are simulated on the phone.\nexport const MOVES = {${out.join(',')}};\n`);
  console.log(`wrote ${COUNT} levels to ${path.relative(process.cwd(), file)}`);
})();
