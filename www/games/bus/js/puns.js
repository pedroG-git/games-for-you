// walks the whole list before repeating (step is coprime with the list length)
window.punFor = function (n) {
  const len = window.PUNS.length;
  const gcd = (a, b) => (b ? gcd(b, a % b) : a);
  let step = 37;
  while (gcd(step, len) !== 1) step++;
  return window.PUNS[(((n - 1) * step) % len + len) % len];
};
