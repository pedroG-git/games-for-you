export const chapterOf = (level) => Math.floor((level - 1) / PER);
export const chapterInfo = (idx) => ({ ...CHAPTERS[idx % CHAPTERS.length], trip: Math.floor(idx / CHAPTERS.length) + 1, idx });

export function renderScene(el, ch, lit, fresh = -1) {
  el.style.setProperty('--sky1', ch.sky[0]);
  el.style.setProperty('--sky2', ch.sky[1]);
  el.style.setProperty('--ground', ch.ground);
  el.innerHTML = '<div class="ground"></div>' + ch.items.map(([e, x, y, s], i) =>
    `<span class="item${i < lit ? ' on' : ''}${i === fresh ? ' new' : ''}" style="left:${x}%;top:${y}%;font-size:calc(var(--sw) * ${s / 360})">${e}</span>`).join('');
}
